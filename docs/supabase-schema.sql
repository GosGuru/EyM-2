-- 1. Habilitar extensiones necesarias
create extension if not exists "uuid-ossp";

-- 2. Tabla de Categorías
create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  name text not null,
  slug text unique not null,
  image text,
  created_at timestamptz default timezone('utc'::text, now()) not null
);

-- 3. Tabla de Productos
create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  slug text unique not null,
  price numeric(10, 2) not null default 0,
  regular_price numeric(10, 2),
  sale_price numeric(10, 2),
  description text,
  short_description text,
  images jsonb default '[]'::jsonb,
  category_slug text references public.categories(slug) on delete set null,
  sizes text[] default array['S', 'M', 'L', 'XL']::text[],
  stock integer default 10,
  featured boolean default false,
  active boolean default true,
  created_at timestamptz default timezone('utc'::text, now()) not null,
  updated_at timestamptz default timezone('utc'::text, now()) not null
);

-- 4. Tabla de Órdenes de Compra
create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  order_key text unique not null,
  status text not null default 'pending', -- pending, processing, completed, cancelled
  total numeric(10, 2) not null default 0,
  currency text not null default 'UYU',
  line_items jsonb not null default '[]'::jsonb,
  shipping_lines jsonb default '[]'::jsonb,
  billing jsonb default '{}'::jsonb,
  shipping jsonb default '{}'::jsonb,
  payment_data jsonb default '{}'::jsonb,
  created_at timestamptz default timezone('utc'::text, now()) not null,
  updated_at timestamptz default timezone('utc'::text, now()) not null
);

-- 5. Índices para acelerar búsquedas
create index if not exists idx_products_slug on public.products(slug);
create index if not exists idx_products_category on public.products(category_slug);
create index if not exists idx_products_featured on public.products(featured) where featured = true;
create index if not exists idx_orders_key on public.orders(order_key);
create index if not exists idx_orders_status on public.orders(status);

-- 6. Configuración de Row Level Security (RLS)
alter table public.categories enable row level security;
alter table public.products enable row level security;
alter table public.orders enable row level security;

-- Políticas de Categorías: Lectura pública, escritura abierta para clave anon/service_role
create policy "Categorias son publicas para lectura" on public.categories
  for select using (true);

create policy "Permitir gestion de categorias" on public.categories
  for all using (true) with check (true);

-- Políticas de Productos: Lectura pública de productos activos
create policy "Productos activos son publicos para lectura" on public.products
  for select using (active = true);

create policy "Permitir gestion de productos en admin" on public.products
  for all using (true) with check (true);

-- Políticas de Órdenes: Creación pública (checkout) y lectura/actualización
create policy "Permitir creacion de ordenes desde checkout" on public.orders
  for insert with check (true);

create policy "Permitir lectura de ordenes" on public.orders
  for select using (true);

create policy "Permitir actualizacion de ordenes (webhooks y admin)" on public.orders
  for update using (true) with check (true);

